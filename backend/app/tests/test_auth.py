def test_register_user(client: TestClient):
    response = client.post(
        "/api/v1/auth/register",
        json={"email": "test@example.com", "password": "password123", "full_name": "Test User"},
    )
    assert response.status_code == 201
    data = response.json()
    assert data["email"] == "test@example.com"
    assert data["full_name"] == "Test User"
    assert "id" in data

def test_register_existing_user_fails(client: TestClient, session: Session):
    # Pre-add user
    hashed = get_password_hash("password123")
    user = User(email="test@example.com", hashed_password=hashed, full_name="Existing")
    session.add(user)
    session.commit()

    response = client.post(
        "/api/v1/auth/register",
        json={"email": "test@example.com", "password": "password123", "full_name": "Test User"},
    )
    assert response.status_code == 400
    assert response.json()["detail"] == "The user with this email already exists in the system."

def test_login_user(client: TestClient, session: Session):
    hashed = get_password_hash("password123")
    user = User(email="test@example.com", hashed_password=hashed, full_name="Test User")
    session.add(user)
    session.commit()

    response = client.post(
        "/api/v1/auth/login",
        data={"username": "test@example.com", "password": "password123"},
    )
    assert response.status_code == 200
    data = response.json()
    assert "access_token" in data
    assert data["token_type"] == "bearer"
